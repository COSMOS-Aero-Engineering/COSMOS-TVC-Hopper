def build(font_path):
    output = Path(__file__).parent / 'images'
    output.mkdir(exist_ok=True)
    fonts = {size: ImageFont.truetype(str(font_path), size) for size in [20,24,28,34]}
    positions = [(40,160),(435,160),(830,160),(40,420),(435,420),(830,420)]
    for name,(title,sub,boxes,edges,foot) in DIAGRAMS.items():
        im = Image.new('RGB',(1220,710),'#f3f6fa')
        d = ImageDraw.Draw(im)
        d.text((40,35),title,font=fonts[34],fill='#162d48')
        d.text((40,95),sub,font=fonts[24],fill='#415971')
        for a,b in edges:
            x,y = positions[a]; xx,yy = positions[b]
            if y==yy:
                p=(x+350,y+90); q=(xx-12,yy+90)
            elif y>yy:
                p=(x+175,y); q=(xx+175,yy+196)
            else:
                p=(x+175,y+180); q=(xx+175,yy-16)
            d.line([p,q],fill='#718da8',width=3)
            import math
            angle=math.atan2(q[1]-p[1],q[0]-p[0])
            tip=(q[0],q[1])
            d.polygon([tip,(tip[0]-13*math.cos(angle-.45),tip[1]-13*math.sin(angle-.45)),(tip[0]-13*math.cos(angle+.45),tip[1]-13*math.sin(angle+.45))],fill='#718da8')
        for (x,y),lines in zip(positions,boxes):
            d.rounded_rectangle((x,y,x+350,y+180),radius=15,fill='white',outline='#a5b8ce',width=2)
            heading_font = fonts[28] if d.textlength(lines[0],font=fonts[28]) <= 314 else fonts[24]
            d.text((x+18,y+22),lines[0],font=heading_font,fill='#174d77')
            for j,line in enumerate(lines[1:]):
                d.text((x+18,y+77+j*38),line,font=fonts[20],fill='#263a50')
        d.text((40,657),foot,font=fonts[20],fill='#415971')
        im.save(output/(name+'.png'),optimize=True)
    print(f'Generated {len(DIAGRAMS)} diagrams')

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font',default='C:/Windows/Fonts/malgun.ttf')
    build(parser.parse_args().font)
